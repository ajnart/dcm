package main

import (
	"fmt"
	"path/filepath"
	"strings"

	"github.com/ajnart/self-host/internal/tui"
)

func writeTheme() error {
	p := tui.DarkColors
	vars := [][2]string{
		{"accent", p.Accent},
		{"accent-text", p.AccentText},
		{"on-accent", p.Ink},
		{"ok", p.OK},
		{"warn", p.Warn},
		{"fail", p.Fail},
		{"info", p.Info},
		{"selected", p.Selected},
	}
	var b strings.Builder
	b.WriteString("/* Generated by go run ./tools/sitegen from the Dashboard's dark palette. */\n:root {\n")
	for _, v := range vars {
		fmt.Fprintf(&b, "  --%s: %s;\n", v[0], strings.ToLower(v[1]))
	}
	b.WriteString("}\n")
	return writeFile(filepath.Join("site", "src", "styles", "theme.css"), []byte(b.String()))
}
