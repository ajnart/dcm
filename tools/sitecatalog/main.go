type appJSON struct {
	ID          string   `json:"id"`
	Name        string   `json:"name"`
	Description string   `json:"d"`
	Category    string   `json:"c"`
	Image       string   `json:"img"`
	Port        int      `json:"p"`
	Links       []string `json:"l"`
	LinkTitles  []string `json:"lt"`
	Icon        string   `json:"i,omitempty"`
}

